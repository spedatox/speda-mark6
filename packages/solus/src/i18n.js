// Money is formatted as decimal text: never round it through a JavaScript Number.
export function formatAmount(value, language = 'tr') {
  if (value === null || value === undefined || value === '') return '—'
  const text = String(value)
  const match = /^(-?)(\d+)(?:\.(\d+))?$/.exec(text)
  if (!match) return text
  const [, sign, whole, fraction] = match
  const group = language === 'tr' ? '.' : ','
  const decimal = language === 'tr' ? ',' : '.'
  return sign + whole.replace(/\B(?=(\d{3})+(?!\d))/g, group) + (fraction === undefined ? '' : decimal + fraction)
}
export function normalizeAmount(value, language = 'tr') {
  if (typeof value !== 'string' || language !== 'tr' || !value.includes(',')) return value
  const text = value.trim()
  if (!/^-?(?:\d+|\d{1,3}(?:\.\d{3})+),\d+$/.test(text)) throw new Error('Enter a valid amount, for example 1.234,56.')
  return text.replaceAll('.', '').replace(',', '.')
}
const monetaryKeys = new Set(['amount','schedule_amount','stated_balance','minimum_due','opening_balance','closing_balance','cost','fee','proceeds','value','quantity'])
export function normalizeAmounts(payload, language) {
  if (Array.isArray(payload)) return payload.map(item => normalizeAmounts(item, language))
  if (!payload || typeof payload !== 'object') return payload
  return Object.fromEntries(Object.entries(payload).map(([key,value]) => [key, monetaryKeys.has(key) ? normalizeAmount(value,language) : (typeof value === 'object' ? normalizeAmounts(value,language) : value)]))
}
export function initialLanguage() {
  try { const saved = localStorage.getItem('solus_language'); if (saved === 'tr' || saved === 'en') return saved } catch {}
  return navigator.language?.toLowerCase().startsWith('tr') ? 'tr' : 'en'
}
export function translate(text, language) {
  return language === 'tr' ? (turkish[text] ?? text) : text
}
