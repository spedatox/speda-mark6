await page.getByLabel('Amount',{exact:true}).fill('1000.00')
await page.getByLabel('Debit account',{exact:true}).selectOption({label:'Shopping · expense · TRY'})
await page.getByLabel('Credit account',{exact:true}).selectOption({label:'My card · liability · TRY'})
await page.getByLabel('Installments',{exact:true}).fill('3')
await page.getByRole('button',{name:'Post transaction',exact:true}).click()
await page.waitForFunction(()=>document.querySelector('main')?.getAttribute('aria-busy')==='false')
assert.ok(await page.getByText('Owner-entered card purchase',{exact:true}).isVisible())
await page.getByLabel('Reporting month',{exact:true}).fill('2026-09')
await page.waitForFunction(()=>document.querySelector('main')?.getAttribute('aria-busy')==='false')
await page.getByRole('button',{name:'Cards & statements',exact:true}).click()
assert.ok((await page.locator('main').innerText()).includes('333.34'))
assert.ok((await page.locator('main').innerText()).includes('2026-09-22'))
await page.screenshot({path:path.join(os.tmpdir(),'solus-statement.png'),fullPage:true})
await page.getByRole('button',{name:'Settings',exact:true}).click()
await page.getByLabel('Current password',{exact:true}).fill('Browser fixture password only')
await page.getByLabel('New password',{exact:true}).fill('Changed browser fixture password')
await page.getByLabel('Confirm new password',{exact:true}).fill('Changed browser fixture password')
await page.getByRole('button',{name:'Change password & sign out',exact:true}).click()
await page.getByLabel('Password',{exact:true}).fill('Changed browser fixture password')
await page.getByRole('button',{name:'Open your books'}).click()
await page.getByRole('button',{name:'Overview',exact:true}).waitFor()
await page.waitForFunction(()=>document.querySelector('main')?.getAttribute('aria-busy')==='false')
await page.getByRole('button',{name:'Overview',exact:true}).click()
const storage=await page.evaluate(()=>({local:Object.keys(localStorage),session:Object.keys(sessionStorage)}))
assert.deepEqual(storage,{local:['solus_language'],session:[]})
await page.getByRole('button',{name:'Reports',exact:true}).click()
