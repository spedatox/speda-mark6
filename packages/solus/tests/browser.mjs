await page.getByRole('button',{name:'Raporlar',exact:true}).waitFor()
await page.getByRole('button',{name:'Raporlar',exact:true}).click()
await page.waitForFunction(()=>document.querySelector('main')?.getAttribute('aria-busy')==='false')
await page.getByText('Teknik defter toplamları',{exact:true}).click()
assert.ok((await page.locator('main').innerText()).includes('1.000,00'))
let releaseRead
const delayedRead = new Promise(resolve => { releaseRead = resolve })
await page.route('**/business?period=2026-08',async route => { await delayedRead; await route.continue() })
await page.getByLabel('Rapor ayı',{exact:true}).fill('2026-08')
await page.locator('.loading-overlay').waitFor({state:'visible'})
assert.ok((await page.locator('.loading-overlay').innerText()).includes('Veriler yükleniyor…'))
assert.ok((await page.locator('.loading-overlay').innerText()).includes('2026-08'))
assert.equal(await page.locator('main').getAttribute('aria-busy'),'true')
releaseRead()
await page.locator('.loading-overlay').waitFor({state:'hidden'})
assert.equal(await page.locator('main').getAttribute('aria-busy'),'false')
await page.unroute('**/business?period=2026-08')
await page.screenshot({path:path.join(os.tmpdir(),'solus-reports-tr.png'),fullPage:true})
await page.getByRole('button',{name:'Genel Bakış',exact:true}).click()
