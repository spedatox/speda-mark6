await page.getByLabel('Days after closing',{exact:true}).fill('10')
await page.getByRole('button',{name:'Save card dates',exact:true}).click()
await page.waitForFunction(()=>document.querySelector('main')?.getAttribute('aria-busy')==='false')
await page.screenshot({path:path.join(os.tmpdir(),'solus-card-settings.png'),fullPage:true})
await page.getByRole('button',{name:'Journal',exact:true}).click()
await page.getByLabel('Operation',{exact:true}).selectOption('card_purchase')
await page.getByLabel('Description',{exact:true}).fill('Owner-entered card purchase')
await page.getByLabel('Occurrence date',{exact:true}).fill('2026-08-11')
