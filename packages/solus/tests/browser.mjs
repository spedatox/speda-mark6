import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
import path from 'node:path'
import os from 'node:os'
const browser = await chromium.launch({headless:true})
const page = await browser.newPage({viewport:{width:1440,height:1100},locale:'en-US'})
const errors=[]
page.on('pageerror',e=>errors.push(e.message))
page.on('console',msg=>{if(msg.type()==='error' && !(msg.location().url.endsWith('/solus/api/v1/session') && msg.text().includes('401'))) errors.push(msg.text())})
const root=process.env.SOLUS_TEST_URL || 'http://127.0.0.1:8767'
await page.goto(root+'/solus/')
await page.getByLabel('Owner API key (first setup only)').fill('solus-browser-fixture-key')
await page.getByLabel('New password',{exact:true}).fill('Browser fixture password only')
await page.getByLabel('Confirm password',{exact:true}).fill('Browser fixture password only')
await page.getByRole('button',{name:'Set password & open Solus'}).click()
await page.getByLabel('Name',{exact:true}).fill('My personal book')
await page.getByRole('button',{name:'Create book',exact:true}).click()
await page.getByRole('button',{name:'Accounts',exact:true}).click()
const accountPanel=page.locator('section').filter({has:page.getByRole('heading',{name:'Add an account',exact:true})})
for(const [name,type] of [['Checking','asset'],['My card','liability'],['Shopping','expense']]){
  await accountPanel.getByLabel('Name',{exact:true}).fill(name)
  await accountPanel.getByLabel('Type',{exact:true}).selectOption(type)
  await accountPanel.getByRole('button',{name:'Add account',exact:true}).click()
  await page.waitForFunction(()=>document.querySelector('main')?.getAttribute('aria-busy')==='false')
}
await page.getByRole('button',{name:'Cards & statements',exact:true}).click()
await page.getByLabel('Card',{exact:true}).selectOption({label:'My card · TRY'})
await page.getByLabel('Statement closing day',{exact:true}).fill('12')
